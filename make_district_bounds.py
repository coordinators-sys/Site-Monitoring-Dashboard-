"""Regenerate district_bounds.py from data/geo.json (district name -> lon/lat bounding box).

The live /api/operational function cannot read data/geo.json at request time, so the
district extents it needs to reject misplaced GPS points are kept as a small Python
module. build_public.py fails the build if this module no longer matches data/geo.json,
so run this whenever the boundary layer changes:

    python make_district_bounds.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def bounds_from_geo(geo):
    out = {}
    for d in geo["districts"]:
        rings = d.get("parts") and [r for p in d["parts"] for r in p] or d.get("rings", [])
        xs = [x for r in rings for x, _ in r]
        ys = [y for r in rings for _, y in r]
        out[d["n"]] = (round(min(xs), 3), round(min(ys), 3), round(max(xs), 3), round(max(ys), 3))
    return dict(sorted(out.items()))


def render(bounds, source):
    lines = ['"""GENERATED by make_district_bounds.py from data/geo.json — do not edit by hand.',
             f"Source layer: {source}",
             'District name -> (min_lon, min_lat, max_lon, max_lat). Used by build_operational.py to drop',
             'site coordinates that fall outside the site\'s own district (e.g. 12.09N typed for 2.09N)."""',
             "BOUNDS = {"]
    lines += [f"    {k!r}: {v!r}," for k, v in bounds.items()]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    geo = json.load(open(os.path.join(HERE, "data", "geo.json"), encoding="utf-8"))
    src = (geo.get("source") or {}).get("districts", "data/geo.json")
    path = os.path.join(HERE, "district_bounds.py")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(bounds_from_geo(geo), src))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
